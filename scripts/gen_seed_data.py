# 输出句式变体：避免全部是「共情，建议。」一种腔调
CHAT_PATTERNS = [
    "{emp}，{adv}。",
    "{emp}。{adv}。",
    "嗯，{adv}。",
    "{adv}。",
]


def gen_chat(per_topic=80):
    rows = []
    for topic in CHAT_TOPICS:
        pool = []
        for utt, advs in topic["items"]:
            for adv in advs:
                for emp in topic["empathy"]:
                    pool.append((utt, emp, adv))
        random.shuffle(pool)
        for utt, emp, adv in pool[:per_topic]:
            text = random.choice(CHAT_PATTERNS).format(emp=emp, adv=adv)
            rows.append(
                {
                    "instruction": utt,
                    "input": "",
                    "output": text,
                    "category": "闲聊",
                }
            )
    return rows


