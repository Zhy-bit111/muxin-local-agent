def gen_reminders(per_task=100):
    rows = []
    for task_name, cfg in REMIND_TASKS.items():
        combos = list(product(ADDRESS, cfg["contexts"], cfg["replies"]))
        random.shuffle(combos)
        for addr, ctx, reply in combos[:per_task]:
            rows.append(
                {
                    "instruction": random.choice(cfg["instructions"]),
                    "input": ctx,
                    "output": addr + reply,
                    "category": "提醒",
                }
            )
    return rows


