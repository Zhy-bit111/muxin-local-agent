CHAT_PREFIX = ["", "嗯，", "诶，", "哈，"]


def gen_chat(per_topic=100):
    rows = []
    for topic in CHAT_TOPICS:
        pool = []
        for sg in topic["subgroups"]:
            for utt, emp, adv in product(sg["utts"], topic["empathy"], sg["advice"]):
                pool.append((utt, emp, adv))
        random.shuffle(pool)
        for utt, emp, adv in pool[:per_topic]:
            prefix = random.choice(CHAT_PREFIX)
            text = f"{prefix}{emp}，{adv}。"
            rows.append(
                {
                    "instruction": utt,
                    "input": "",
                    "output": text,
                    "category": "闲聊",
                }
            )
    return rows


