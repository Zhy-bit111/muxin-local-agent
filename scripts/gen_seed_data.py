def gen_boundary():
    rows = []
    for instr, replies in BOUNDARY:
        for reply in replies:
            rows.append(
                {
                    "instruction": instr,
                    "input": "",
                    "output": reply,
                    "category": "边界",
                }
            )
    return rows


def main():
    rows = []
    rows += gen_reminders(per_task=100)   # 5 任务 × 100 = 500
    rows += gen_chat(per_topic=80)        # 18 主题 × 80 = 1440
    rows += gen_boundary()                # 63 × 3 = 189

    # 去重：按 (instruction, input, output) 整行判断
    # 注意：不能只按 output 去重——同一句提醒配不同时间上下文是有效样本
    seen = set()
    uniq = []
    for r in rows:
        key = (
            r["instruction"].strip(),
            r["input"].strip(),
            r["output"].strip(),
        )
        if key in seen:
            continue
        seen.add(key)
        uniq.append(r)

    random.shuffle(uniq)

    with OUT.open("w", encoding="utf-8") as f:
        for r in uniq:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    from collections import Counter

    cnt = Counter(r["category"] for r in uniq)
    print(f"written: {OUT}")
    print(f"total: {len(uniq)}")
    for k, v in cnt.items():
        print(f"  {k}: {v}")


if __name__ == "__main__":
    main()
